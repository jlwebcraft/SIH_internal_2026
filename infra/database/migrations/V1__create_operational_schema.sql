CREATE INDEX idx_supplier_materials_material_id ON supplier_materials (material_id);
CREATE INDEX idx_product_materials_product_id ON product_materials (product_id);
CREATE INDEX idx_product_materials_material_id ON product_materials (material_id);
CREATE INDEX idx_inventories_material_id ON inventories (material_id);
CREATE INDEX idx_purchase_orders_supplier_id ON purchase_orders (supplier_id);
CREATE INDEX idx_purchase_orders_created_by ON purchase_orders (created_by);
CREATE INDEX idx_purchase_order_items_purchase_order_id ON purchase_order_items (purchase_order_id);
CREATE INDEX idx_purchase_order_items_material_id ON purchase_order_items (material_id);
CREATE INDEX idx_deliveries_purchase_order_id ON deliveries (purchase_order_id);
CREATE INDEX idx_supplier_performances_supplier_id ON supplier_performances (supplier_id);
CREATE INDEX idx_production_orders_product_id ON production_orders (product_id);
CREATE INDEX idx_production_orders_created_by ON production_orders (created_by);
CREATE INDEX idx_customer_order_items_customer_order_id ON customer_order_items (customer_order_id);
CREATE INDEX idx_customer_order_items_product_id ON customer_order_items (product_id);

